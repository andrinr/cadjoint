"""Write frontend/src/scene/templates.generated.ts from the Python shader templates.

The preview, path-tracer and present shaders are fixed WGSL around the scene
code, and the Python viewer modules hold the one copy of each.  This copies
them into a module the browser can import, so the frontend assembles the same
three shaders the worker does.  ``tests/backends/test_wgsl_frontend.py`` fails
when the file is out of date.

Run from the repository root::

    python frontend/tools/emit_wgsl_templates.py
"""

from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "scene" / "templates.generated.ts"


def templates_ts() -> str:
    from cadjoint.viewer import _pathtracer, _webgpu

    constants = {
        "SDF_MARKER": _webgpu._SDF_MARKER,
        "SCENE_MARKER": _pathtracer._SCENE_MARKER,
        "DEFAULT_MATERIAL_WGSL": _webgpu.DEFAULT_MATERIAL_WGSL,
        "WGSL_VIEWER_TEMPLATE": _webgpu.WGSL_VIEWER_TEMPLATE,
        "WGSL_PATH_TRACER_TEMPLATE": _pathtracer.WGSL_PATH_TRACER_TEMPLATE,
        "WGSL_PRESENT_TEMPLATE": _pathtracer.WGSL_PRESENT_TEMPLATE,
    }
    lines = [
        "// GENERATED by frontend/tools/emit_wgsl_templates.py from",
        "// cadjoint/viewer/_webgpu.py and _pathtracer.py. Do not edit: change the",
        "// Python and re-run.",
    ]
    for name, value in constants.items():
        lines.append(f"export const {name} = {json.dumps(value)};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(templates_ts())
    print(f"wrote {OUT}")
