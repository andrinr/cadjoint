"""jax-js backend: cadjoint's field as generated TypeScript for the browser.

Each node type's ``sdf`` is traced with JAX, exported to StableHLO and
translated op by op into a jax-js function (:mod:`.kernels`).  A scene is a
JSON graph of those node types (:mod:`.scene`), which the browser runtime
composes.  The maths stays in cadjoint's Python; nothing here restates it.

Command line::

    python -m cadjoint.backends.jaxjs kernels OUT.ts
    python -m cadjoint.backends.jaxjs scene SCENE.py OUT.json
"""

from __future__ import annotations

from .kernels import NODE_TYPES, POLYGON_BUCKETS, kernel_sets
from .scene import SCENE_FORMAT, SCENE_VERSION, UnsupportedNode, graph_sdf, scene_graph

__all__ = [
    "NODE_TYPES",
    "POLYGON_BUCKETS",
    "SCENE_FORMAT",
    "SCENE_VERSION",
    "UnsupportedNode",
    "graph_sdf",
    "kernels_ts",
    "scene_graph",
]

_HEADER = """\
// GENERATED by `python -m cadjoint.backends.jaxjs kernels` from cadjoint's
// own SDF code via StableHLO. Do not edit: change the Python and re-run.
/* eslint-disable */
import { numpy as np } from "@jax-js/jax";
"""


def kernels_ts(names=None) -> str:
    """The TypeScript module holding every node type's kernels and their registry.

    Args:
        names: Scene-graph type names to emit; all when None.

    Returns:
        The module source.  It exports ``nodeTypes``: per type, its kind,
        parameter names, static parameters, arity, and kernels by role.
    """
    sets = kernel_sets(names)
    parts = [_HEADER]
    for ks in sets:
        parts.extend(ks.sources)
        parts.append("")
    parts.append('export type NodeKind = "primitive" | "operation" | "pattern";')
    parts.append("export type Kernel = (...args: np.Array[]) => np.Array;")
    parts.append(
        "export type NodeType = { kind: NodeKind; params: string[]; static: string[];"
        " nary: boolean; kernels: Record<string, Kernel> };"
    )
    parts.append(f"export const polygonBuckets = {list(POLYGON_BUCKETS)};")
    parts.append(
        f'export const sceneFormat = {{ format: "{SCENE_FORMAT}", version: {SCENE_VERSION} }};'
    )
    parts.append("export const nodeTypes: Record<string, NodeType> = {")
    for ks in sets:
        node = ks.node
        fns = ", ".join(f"{role}: {fn}" for role, fn in ks.fns.items())
        params = ", ".join(f'"{p}"' for p in node.params)
        static = ", ".join(f'"{p}"' for p in node.static)
        parts.append(
            f'  {node.name}: {{ kind: "{node.kind}", params: [{params}], static: [{static}],'
            f" nary: {'true' if node.nary else 'false'}, kernels: {{ {fns} }} }},"
        )
    parts.append("};")
    return "\n".join(parts) + "\n"
